/**
 * Contract of APPOINTMENT_REQUEST_CREATED (event version 2).
 *
 * Emitted (through the outbox) by whoever takes the booking: backend-dating-business-owner for
 * the owner/staff, backend-dating-user for customers. backend-dating-schedule is the only
 * service that decides: it creates the request row from this payload (idempotent by requestId),
 * validates and turns it into an appointment, or rejects it.
 *
 * The emitter validates what it owns (business hours, service window, advance rules, team
 * member) before emitting; schedule re-validates against its own projections and is the
 * arbiter of slot availability.
 */

export type PaymentMethodContract = 'cash' | 'bank_transfer';

export interface CustomerContactInfoContract {
  name: string;
  email: string;
  phone: string;
  identityNumber?: string;
}

export interface AppointmentRequestCreatedData {
  /** Generated by the emitter; makes the request idempotent */
  requestId: string;
  /** Business that owns the agenda */
  tenantId: string;
  serviceId: string;
  teamMemberId: string | null;
  /** null = guest booking */
  customerTenantId: string | null;
  customerUserId: string | null;
  customerContactInfo: CustomerContactInfoContract;
  /** ISO 8601 (UTC) */
  scheduledAt: string;
  scheduledEndAt: string;
  durationMinutes: number;
  /** Copied from the service at request time */
  price: number;
  currency: string;
  paymentMethod: PaymentMethodContract;
  customerNotes: string | null;
  /** User who took the booking (owner/staff/customer); null for guests */
  requestedBy: string | null;
  origin: 'business' | 'customer';
}

/** APPOINTMENT_REQUEST_REJECTED */
export interface AppointmentRequestRejectedData {
  requestId: string;
  tenantId: string;
  reason: string;
}
